//! # cow-rs
//!
//! Rust SDK for the [CoW Protocol](https://cow.fi).
//!
//! This crate is in early development. Public surface is intentionally narrow
//! and grows feature-by-feature so each addition can be reviewed in isolation.
//!
//! ## Parity references
//!
//! - [`cowprotocol/cow-sdk`](https://github.com/cowprotocol/cow-sdk) (TypeScript)
